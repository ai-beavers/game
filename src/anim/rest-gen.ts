// Writes rest.ts: each bone's rest transform as assets/beaver.glb holds it, so the animator needs no glb at run
// time. Run again whenever the beaver is rebuilt:  bun src/anim/rest-gen.ts
import { BONES } from "../contracts.ts";
import { parseGlb } from "./glb.ts";
import { mul, rotate, add, type Quat, type Vec } from "./quat.ts";

const glb = parseGlb(new Uint8Array(await Bun.file(new URL("../../assets/beaver.glb", import.meta.url)).arrayBuffer()));
const nodes: any[] = glb.json.nodes;
const index = new Map(nodes.map((n, i) => [n.name as string, i]));
const parentOf = new Map<number, number>();
nodes.forEach((n, i) => (n.children ?? []).forEach((c: number) => parentOf.set(c, i)));
const rig = index.get("rig")!;
if (nodes[rig].rotation || nodes[rig].translation) throw new Error("rig node moved: rest.ts assumes it is not");

const round = (v: number[]) => v.map((x) => Math.round(x * 1e7) / 1e7);
const rest: Record<string, unknown> = {};
// armature-space orientation and position, walking down from the rig
const world = new Map<number, { q: Quat; p: Vec }>();
const place = (i: number): { q: Quat; p: Vec } => {
  if (i === rig) return { q: [0, 0, 0, 1], p: [0, 0, 0] };
  const known = world.get(i);
  if (known) return known;
  const n = nodes[i], up = place(parentOf.get(i)!);
  const q: Quat = n.rotation ?? [0, 0, 0, 1], t: Vec = n.translation ?? [0, 0, 0];
  const at = { q: mul(up.q, q), p: add(up.p, rotate(up.q, t)) };
  world.set(i, at);
  return at;
};
for (const bone of BONES) {
  const i = index.get(bone)!, n = nodes[i], parent = nodes[parentOf.get(i)!].name;
  const at = place(i);
  rest[bone] = {
    parent: (BONES as readonly string[]).includes(parent) ? parent : null,
    rotation: round(n.rotation ?? [0, 0, 0, 1]), translation: round(n.translation ?? [0, 0, 0]),
    armatureRotation: round(at.q), armaturePosition: round(at.p),
  };
}
const text = `// Generated by rest-gen.ts from assets/beaver.glb; do not edit. Each bone at rest: its local transform as glTF
// holds it, and its orientation and head position in the armature's space (glTF axes: y up, the beaver faces +z).
import type { Bone } from "../contracts.ts";
import type { Quat, Vec } from "./quat.ts";

export interface RestBone { parent: Bone | null; rotation: Quat; translation: Vec; armatureRotation: Quat; armaturePosition: Vec }

export const REST: Record<Bone, RestBone> = {
${Object.entries(rest).map(([k, v]) => `  ${k}: ${JSON.stringify(v).replace(/"(\w+)":/g, "$1: ").replace(/,/g, ", ")},`).join("\n")}
};
`;
await Bun.write(new URL("./rest.ts", import.meta.url), text);
console.log("wrote rest.ts");
